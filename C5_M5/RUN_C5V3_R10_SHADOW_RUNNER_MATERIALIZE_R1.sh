hash1() {
  sha256sum "$1" 2>/dev/null | awk '{print $1}'
}

hold() {
  printf 'SHADOW_RUNNER_MATERIALIZE=HOLD_%s\n' "$1"
  printf 'SHADOW_RUNNER_EXECUTION=NO\n'
  printf 'PRODUCTION_BINDING=NO\n'
  printf 'PRODUCTION_MUTATION=NO\n'
  exit 0
}

require_hash() {
  label="$1"
  path="$2"
  expected="$3"
  [ -f "$path" ] || hold "${label}_MISSING"
  actual=$(hash1 "$path")
  printf '%s_PATH=%s\n' "$label" "$path"
  printf '%s_SHA256=%s\n' "$label" "$actual"
  [ "$actual" = "$expected" ] || hold "${label}_IDENTITY_MISMATCH"
  printf '%s_IDENTITY=PASS\n' "$label"
}

extract_assign() {
  var="$1"
  count=$(grep -Ec "^${var}=" "$LIVE_RUNNER" 2>/dev/null || true)
  [ "$count" -eq 1 ] || hold "RUNNER_${var}_ASSIGNMENT_COUNT_${count}"
  raw=$(grep -E "^${var}=" "$LIVE_RUNNER" | head -n 1)
  raw=${raw#*=}
  case "$raw" in
    \"*\") raw=${raw#\"}; raw=${raw%\"} ;;
    \'*\') raw=${raw#\'}; raw=${raw%\'} ;;
  esac
  printf '%s' "$raw"
}

stage_copy_exact() {
  label="$1"
  src="$2"
  dst="$3"
  expected="$4"
  if [ -f "$dst" ]; then
    actual=$(hash1 "$dst")
    [ "$actual" = "$expected" ] || hold "EXISTING_${label}_MISMATCH"
    printf '%s_STAGE_EXISTING=PASS\n' "$label"
    return 0
  fi
  cp "$src" "$dst.partial"
  actual=$(hash1 "$dst.partial")
  [ "$actual" = "$expected" ] || hold "${label}_COPY_MISMATCH"
  mv "$dst.partial" "$dst"
  printf '%s_STAGE_COPY=PASS\n' "$label"
}

