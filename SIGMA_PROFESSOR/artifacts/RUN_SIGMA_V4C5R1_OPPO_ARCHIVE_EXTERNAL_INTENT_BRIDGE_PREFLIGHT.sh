make_case() {
    NAME="$1"
    ROOT="$BASE/$NAME"
    BRAIN="$ROOT/BRAIN/EXTRA BRAIN_OPPO_24826"
    E="$BRAIN/.sigma_exec"
    mkdir -p "$E"
    for F in \
      SIGMA_V4C5R1_LOCAL_CATALOG_PAGE.memory \
      SIGMA_V4C5R1_LOCAL_CATALOG_PAGE_ID.memory \
      SIGMA_V4C5R1_LOCAL_CURSOR.memory \
